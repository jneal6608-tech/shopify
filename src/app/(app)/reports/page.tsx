import Link from "next/link";
import { requireUser } from "@/lib/auth/session";
import { withUser } from "@/lib/db";
import { activeWeights } from "@/lib/services/scoring";
import { suggestWeights, type OutcomeSample } from "@/lib/analytics/learning";
import { COMPONENT_LABELS, type ComponentKey } from "@/lib/analytics/weights";
import { FACELESS_FORMATS } from "@/lib/analytics/rubrics";
import { Badge, Card, CardBody, CardHeader, Notice, PageHeader, Stat, Table, TabLinks, Td, Th } from "@/components/ui/primitives";
import { DemoBadge } from "@/components/ui/domain";
import { ActionButton } from "@/components/ui/action";
import { fmtDate, fmtPct } from "@/lib/utils";

export const metadata = { title: "Reports" };

export default async function ReportsPage({ searchParams }: { searchParams: Promise<{ tab?: string }> }) {
  const user = await requireUser();
  const tab = ["reports", "recommendations", "insights"].includes((await searchParams).tab ?? "") ? (await searchParams).tab! : "reports";
  const d = await withUser(user.id, async (db) => ({
    reports: await db<Array<{ id: string; kind: string; title: string; model: string | null; createdAt: Date; isDemo: boolean }>>`select id, kind, title, model, created_at, is_demo from public.research_reports order by created_at desc limit 200`,
    recs: await db<Array<{ id: string; productId: string | null; productName: string | null; context: string; recommendation: string; confidence: number; scoreTotal: number | null; outcome: string | null; createdAt: Date }>>`
      select r.*, p.name as product_name from public.ai_recommendations r left join public.products p on p.id = r.product_id order by r.created_at desc limit 200`,
    samples: await db<Array<{ productId: string; outcome: OutcomeSample["outcome"]; components: Array<{ key: ComponentKey; score: number | null }> | null; isDemo: boolean }>>`
      select distinct on (d.product_id) d.product_id, d.outcome, p.is_demo,
        (select s.components from public.product_scores s where s.product_id = d.product_id and s.computed_at <= d.created_at order by s.computed_at desc limit 1) as components
      from public.product_decisions d join public.products p on p.id = d.product_id
      where d.outcome is not null order by d.product_id, d.created_at desc`,
    decisions: await db<Array<{ decision: string; n: number }>>`select decision, count(*)::int as n from public.product_decisions group by decision`,
    margins: await db<Array<{ name: string; est: number | null; actual: number }>>`
      select p.name, p.est_gross_margin_pct as est, d.actual_margin_pct as actual from public.product_decisions d join public.product_overview p on p.id = d.product_id where d.actual_margin_pct is not null order by d.created_at desc limit 20`,
    formats: await db<Array<{ format: string; outcome: string; videos: number; clicks: number; views: number }>>`
      select v.format, o.outcome, count(*)::int as videos, coalesce(sum(l.link_clicks), 0)::bigint as clicks, coalesce(sum(l.views), 0)::bigint as views
      from public.published_videos v
      join lateral (select outcome from public.product_decisions d where d.product_id = v.product_id and d.outcome is not null order by created_at desc limit 1) o on true
      left join lateral (select * from public.video_performance x where x.video_id = v.id order by captured_at desc limit 1) l on true
      group by v.format, o.outcome order by v.format`,
    weights: await activeWeights(db, user.id),
  }));
  const samples: OutcomeSample[] = d.samples.filter((s) => !s.isDemo).map((s) => ({ productId: s.productId, outcome: s.outcome, components: Object.fromEntries((s.components ?? []).map((c) => [c.key, c.score])) }));
  const learning = suggestWeights(samples, d.weights.weights);
  const evaluated = d.recs.filter((r) => r.outcome && r.outcome !== "not_tested");
  const hits = evaluated.filter((r) => r.outcome === "performed_well").length;
  return (
    <>
      <PageHeader title="Reports" description="Research reports, the history of past recommendations measured against real outcomes, and what your testing history suggests." />
      <TabLinks active={tab} tabs={[{ key: "reports", label: "Research reports", href: "/reports", count: d.reports.length }, { key: "recommendations", label: "Recommendation history", href: "/reports?tab=recommendations", count: d.recs.length }, { key: "insights", label: "Learning insights", href: "/reports?tab=insights" }]} />
      {tab === "reports" && (
        <Card>
          <Table>
            <thead><tr><Th>Report</Th><Th>Type</Th><Th>Generated by</Th><Th>Date</Th></tr></thead>
            <tbody>
              {d.reports.length === 0 && <tr><Td colSpan={4} className="text-center text-xs text-muted">No reports yet.</Td></tr>}
              {d.reports.map((r) => <tr key={r.id}><Td><Link href={`/reports/${r.id}`} className="hover:text-accent">{r.title}</Link> {r.isDemo && <DemoBadge />}</Td><Td className="text-xs text-muted">{r.kind.replace(/_/g, " ")}</Td><Td>{r.model ? <Badge tone="accent">{r.model}</Badge> : <Badge tone="good">deterministic</Badge>}</Td><Td className="whitespace-nowrap text-xs text-faint">{fmtDate(r.createdAt, true)}</Td></tr>)}
            </tbody>
          </Table>
        </Card>
      )}
      {tab === "recommendations" && (
        <>
          <div className="mb-5 grid gap-3 sm:grid-cols-3">
            <Stat label="Recommendations made" value={d.recs.length} />
            <Stat label="With known outcomes" value={evaluated.length} />
            <Stat label="Performed well" value={evaluated.length ? fmtPct((hits / evaluated.length) * 100, 0) : "—"} sub="share of tested recommendations" />
          </div>
          <Card>
            <Table>
              <thead><tr><Th>Date</Th><Th>Product</Th><Th>Context</Th><Th>Recommendation</Th><Th className="text-right">Score</Th><Th className="text-right">Conf.</Th><Th>Outcome</Th></tr></thead>
              <tbody>
                {d.recs.map((r) => (
                  <tr key={r.id}>
                    <Td className="whitespace-nowrap text-xs text-faint">{fmtDate(r.createdAt)}</Td>
                    <Td>{r.productId ? <Link href={`/products/${r.productId}`} className="hover:text-accent">{r.productName}</Link> : "—"}</Td>
                    <Td className="text-xs">{r.context.replace(/_/g, " ")}</Td>
                    <Td className="max-w-md text-xs text-muted">{r.recommendation}</Td>
                    <Td className="text-right tabular-nums">{r.scoreTotal ?? "—"}</Td>
                    <Td className="text-right tabular-nums">{r.confidence}</Td>
                    <Td>{r.outcome ? <Badge tone={r.outcome === "performed_well" ? "good" : r.outcome === "performed_poorly" ? "bad" : "neutral"}>{r.outcome.replace(/_/g, " ")}</Badge> : <span className="text-xs text-faint">pending</span>}</Td>
                  </tr>
                ))}
              </tbody>
            </Table>
            <CardBody className="text-xs text-faint">Outcomes are recorded when you log a decision with an outcome on the product's Research history tab.</CardBody>
          </Card>
        </>
      )}
      {tab === "insights" && (
        <div className="grid gap-5 xl:grid-cols-2">
          <Card>
            <CardHeader title="Scoring-weight suggestion" description={`Active weights: version ${d.weights.version}`} />
            <CardBody className="space-y-3 text-sm">
              <Notice>{learning.note}</Notice>
              <Table>
                <thead><tr><Th>Component</Th><Th className="text-right">Weight</Th><Th className="text-right">Did well (avg)</Th><Th className="text-right">Did poorly (avg)</Th><Th className="text-right">Difference</Th></tr></thead>
                <tbody>{learning.evidence.map((e) => <tr key={e.key}><Td className="text-xs">{COMPONENT_LABELS[e.key]}</Td><Td className="text-right">{d.weights.weights[e.key]}%</Td><Td className="text-right tabular-nums">{e.wellMean ?? "—"}</Td><Td className="text-right tabular-nums">{e.poorMean ?? "—"}</Td><Td className="text-right tabular-nums">{e.diff ?? "—"}</Td></tr>)}</tbody>
              </Table>
              {learning.suggestion && (
                <div className="rounded-lg border border-accent/40 bg-accent/5 p-3 text-xs">
                  <p className="text-fg">{learning.suggestion.reason}</p>
                  <p className="mt-1 text-muted">Proposed: {COMPONENT_LABELS[learning.suggestion.increase]} → {learning.suggestion.weights[learning.suggestion.increase]}%, {COMPONENT_LABELS[learning.suggestion.decrease]} → {learning.suggestion.weights[learning.suggestion.decrease]}%.</p>
                  <div className="mt-2"><ActionButton size="sm" endpoint="/api/settings/weights" method="PUT" body={{ weights: learning.suggestion.weights, reason: learning.suggestion.reason, source: "accepted_suggestion" }} confirm="Create a new scoring-weight version from this suggestion? All products will be rescored and the change is logged.">Accept suggestion</ActionButton></div>
                </div>
              )}
              <p className="text-[11px] text-faint">Demo products are excluded. Weights only change when you accept; each change creates a new version shown in Settings and in every product's score history.</p>
            </CardBody>
          </Card>
          <div className="space-y-5">
            <Card>
              <CardHeader title="Decisions recorded" />
              <CardBody className="flex flex-wrap gap-2">{d.decisions.length === 0 ? <p className="text-xs text-muted">None yet.</p> : d.decisions.map((x) => <Badge key={x.decision}>{x.decision}: {x.n}</Badge>)}</CardBody>
            </Card>
            <Card>
              <CardHeader title="Content formats vs. product outcomes" />
              {d.formats.length === 0 ? <CardBody><p className="text-xs text-muted">Appears once tested products have outcomes and published videos.</p></CardBody> : (
                <Table>
                  <thead><tr><Th>Format</Th><Th>Outcome</Th><Th className="text-right">Videos</Th><Th className="text-right">CTR</Th></tr></thead>
                  <tbody>{d.formats.map((f, i) => <tr key={i}><Td className="text-xs">{FACELESS_FORMATS.find((x) => x.key === f.format)?.label ?? (f.format || "unspecified")}</Td><Td className="text-xs">{f.outcome.replace(/_/g, " ")}</Td><Td className="text-right">{f.videos}</Td><Td className="text-right tabular-nums">{fmtPct(f.views ? (f.clicks / f.views) * 100 : null, 2)}</Td></tr>)}</tbody>
                </Table>
              )}
            </Card>
            <Card>
              <CardHeader title="Estimated vs actual margins" />
              {d.margins.length === 0 ? <CardBody><p className="text-xs text-muted">Record actual margins with decisions to calibrate your estimates.</p></CardBody> : (
                <Table><thead><tr><Th>Product</Th><Th className="text-right">Estimated gross</Th><Th className="text-right">Actual</Th></tr></thead><tbody>{d.margins.map((m, i) => <tr key={i}><Td>{m.name}</Td><Td className="text-right">{fmtPct(m.est, 0)}</Td><Td className="text-right">{fmtPct(m.actual, 0)}</Td></tr>)}</tbody></Table>
              )}
            </Card>
          </div>
        </div>
      )}
    </>
  );
}
