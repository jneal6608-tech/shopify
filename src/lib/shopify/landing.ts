import type { LandingPage } from "../ai/schemas";

/**
 * Escapes text for safe inclusion in Liquid/HTML: HTML entities plus Liquid
 * delimiters, so generated copy can never execute as Liquid or script.
 */
export function escapeLiquid(s: string): string {
  return s
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&#39;")
    .replace(/\{/g, "&#123;")
    .replace(/\}/g, "&#125;")
    .replace(/%/g, "&#37;");
}

export function landingHandle(input: string): string {
  return input.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "").slice(0, 40) || "product";
}

const safeColor = (c: string) => (/^#[0-9a-fA-F]{6}$/.test(c) ? c : "#2563eb");

/** Builds a self-contained, mobile-first Online Store 2.0 section for a product landing page. */
export function buildLandingSection(lp: LandingPage, handle: string): string {
  const e = escapeLiquid;
  const accent = safeColor(lp.accentColor);
  const cls = `di-lp-${handle}`;
  const benefits = lp.benefits.map((b) => `<div class="${cls}__card"><h3>${e(b.title)}</h3><p>${e(b.body)}</p></div>`).join("\n        ");
  const specs = lp.specs.map((s) => `<tr><th>${e(s.label)}</th><td>${e(s.value)}</td></tr>`).join("\n          ");
  const faqs = lp.faqs.map((f) => `<details class="${cls}__faq"><summary>${e(f.q)}</summary><p>${e(f.a)}</p></details>`).join("\n      ");
  const trust = lp.trustPoints.map((t) => `<li>${e(t)}</li>`).join("");
  return `{%- comment -%} Generated by Dropship Intel. Review before publishing. {%- endcomment -%}
{%- assign product = section.settings.product -%}
<style>
  .${cls}{--accent:${accent};max-width:1100px;margin:0 auto;padding:24px 16px;font-family:inherit}
  .${cls} h1{font-size:clamp(28px,6vw,48px);line-height:1.1;margin:0 0 12px}
  .${cls} h2{font-size:clamp(22px,4.5vw,32px);margin:40px 0 12px}
  .${cls}__hero{display:grid;gap:24px;align-items:center}
  @media(min-width:768px){.${cls}__hero{grid-template-columns:1fr 1fr}.${cls}__grid{grid-template-columns:repeat(3,1fr)}}
  .${cls}__hero img{width:100%;height:auto;border-radius:12px}
  .${cls}__sub{font-size:18px;opacity:.8;margin-bottom:16px}
  .${cls}__btn{display:block;width:100%;padding:16px;border:0;border-radius:10px;background:var(--accent);color:#fff;font-size:17px;font-weight:600;cursor:pointer}
  .${cls}__grid{display:grid;gap:16px}
  .${cls}__card{padding:18px;border-radius:12px;background:rgba(0,0,0,.04)}
  .${cls}__card h3{margin:0 0 6px;font-size:17px}
  .${cls} table{width:100%;border-collapse:collapse}.${cls} th,.${cls} td{padding:10px;border-bottom:1px solid rgba(0,0,0,.08);text-align:left}
  .${cls}__faq{padding:14px 0;border-bottom:1px solid rgba(0,0,0,.08)}.${cls}__faq summary{font-weight:600;cursor:pointer}
  .${cls}__trust{display:flex;flex-wrap:wrap;gap:8px 20px;padding:0;list-style:none;opacity:.85;font-size:14px}
  .${cls}__sticky{position:sticky;bottom:0;padding:10px 0;background:inherit}
</style>
<div class="${cls}">
  <div class="${cls}__hero">
    <div>{%- if product.featured_media -%}{{ product.featured_media | image_url: width: 1000 | image_tag: loading: 'eager', alt: product.title }}{%- endif -%}</div>
    <div>
      <h1>${e(lp.headline)}</h1>
      <p class="${cls}__sub">${e(lp.subheadline)}</p>
      {%- if product -%}
      <p><strong>{{ product.price | money }}</strong>{%- if product.compare_at_price > product.price -%} <s>{{ product.compare_at_price | money }}</s>{%- endif -%}</p>
      {%- form 'product', product -%}
        <input type="hidden" name="id" value="{{ product.selected_or_first_available_variant.id }}">
        {%- if product.has_only_default_variant == false -%}
        <select name="id" style="width:100%;padding:12px;margin-bottom:10px">{%- for v in product.variants -%}<option value="{{ v.id }}" {% unless v.available %}disabled{% endunless %}>{{ v.title }} — {{ v.price | money }}</option>{%- endfor -%}</select>
        {%- endif -%}
        <button type="submit" class="${cls}__btn" {% unless product.available %}disabled{% endunless %}>${e(lp.ctaText)}</button>
      {%- endform -%}
      {%- endif -%}
      <ul class="${cls}__trust">${trust}</ul>
    </div>
  </div>
  <h2>${e(lp.problemTitle)}</h2>
  <p>${e(lp.problemBody)}</p>
  <h2>${e(lp.solutionTitle)}</h2>
  <p>${e(lp.solutionBody)}</p>
  <h2>${e(lp.demoTitle)}</h2>
  <p>${e(lp.demoBody)}</p>
  {%- if section.settings.video_url != blank -%}<div style="margin-top:12px">{{ section.settings.video_url | video_tag: controls: true, muted: true, loop: true, playsinline: true }}</div>{%- endif -%}
  <h2>Why you'll love it</h2>
  <div class="${cls}__grid">
        ${benefits}
  </div>
  <h2>Specifications</h2>
  <table>
          ${specs}
  </table>
  <h2>Frequently asked questions</h2>
      ${faqs}
  {%- if product -%}
  <div class="${cls}__sticky">{%- form 'product', product -%}<input type="hidden" name="id" value="{{ product.selected_or_first_available_variant.id }}"><button type="submit" class="${cls}__btn">${e(lp.ctaText)}</button>{%- endform -%}</div>
  {%- endif -%}
</div>
{% schema %}
{
  "name": "DI landing ${handle.slice(0, 12)}",
  "settings": [
    { "type": "product", "id": "product", "label": "Product" },
    { "type": "video", "id": "video_url", "label": "Demo video (upload in Shopify)" }
  ]
}
{% endschema %}
`;
}

export function buildLandingTemplate(sectionType: string, productHandle: string | null): string {
  return JSON.stringify(
    { sections: { main: { type: sectionType, settings: productHandle ? { product: productHandle } : {} } }, order: ["main"] },
    null,
    2,
  );
}
